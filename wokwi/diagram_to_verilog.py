"""
diagram_to_verilog.py - independent check of the generated Wokwi circuit.

Reads diagram.json (NOT the Yosys netlist), joins the wires into nets exactly
as Wokwi does, and writes a Verilog module `tt_um_duarte_diamantino_pid8` made of behavioural
models of the Wokwi logic parts, with the Arduino Mega pins mapped back to the
Tiny Tapeout ports. sim/tb_pid8.v can then be run on the circuit that is
really in the diagram (wiring, part types and pin names included).

Part models follow what was measured in the Wokwi simulator:
  * mux-2: SEL = 0 -> A, SEL = 1 -> B
  * flip-flops: rising edge; flip-flop-dsr: S and R asynchronous, active high,
    R wins; flip-flop-d starts with Q = 1, flip-flop-dsr with Q = 0

Usage: python3 diagram_to_verilog.py diagram.json build/pid8_gates.v
"""
import json
import sys
from collections import defaultdict

SRC = sys.argv[1] if len(sys.argv) > 1 else "diagram.json"
DST = sys.argv[2] if len(sys.argv) > 2 else "build/pid8_gates.v"

MODEL = {   # part type -> (verilog module, inputs, outputs)
    "wokwi-gate-and-2": ("wk_and2", ["A", "B"], ["OUT"]),
    "wokwi-gate-or-2": ("wk_or2", ["A", "B"], ["OUT"]),
    "wokwi-gate-xor-2": ("wk_xor2", ["A", "B"], ["OUT"]),
    "wokwi-gate-nand-2": ("wk_nand2", ["A", "B"], ["OUT"]),
    "wokwi-gate-nor-2": ("wk_nor2", ["A", "B"], ["OUT"]),
    "wokwi-gate-xnor-2": ("wk_xnor2", ["A", "B"], ["OUT"]),
    "wokwi-gate-not": ("wk_not", ["IN"], ["OUT"]),
    "wokwi-gate-buffer": ("wk_buf", ["IN"], ["OUT"]),
    "wokwi-mux-2": ("wk_mux2", ["A", "B", "SEL"], ["OUT"]),
    "wokwi-flip-flop-d": ("wk_ffd", ["D", "CLK"], ["Q"]),
    "wokwi-flip-flop-dsr": ("wk_ffdsr", ["D", "CLK", "S", "R"], ["Q"]),
}
HOST_IN = {f"mega:{22 + i}": f"ui_in[{i}]" for i in range(8)}
HOST_IN.update({"mega:2": "uio_in[0]", "mega:3": "uio_in[1]", "mega:5": "uio_in[2]",
                "mega:6": "rst_n", "mega:11": "clk"})
HOST_OUT = {f"mega:{37 - i}": f"uo_out[{i}]" for i in range(8)}
HOST_OUT.update({"mega:12": "uio_out[3]", "mega:7": "uio_out[4]", "mega:8": "uio_out[5]",
                 "mega:9": "uio_out[6]", "mega:10": "uio_out[7]"})
IGNORE = ("wokwi-arduino-mega", "chip-plant8", "wokwi-potentiometer",
          "wokwi-slide-switch", "wokwi-text")

d = json.load(open(SRC))
ptype = {p["id"]: p["type"] for p in d["parts"]}

parent = {}


def find(x):
    while parent.setdefault(x, x) != x:
        parent[x] = parent[parent[x]]
        x = parent[x]
    return x


for a, b, *_ in d["connections"]:
    parent[find(a)] = find(b)

nets = defaultdict(list)
for x in list(parent):
    nets[find(x)].append(x)

netname = {}
for i, root in enumerate(sorted(nets)):
    netname[root] = f"n{i}"


def net_of(pin):
    return netname[find(pin)] if pin in parent else None


lines = ["// generated by diagram_to_verilog.py from diagram.json - do not edit",
         "`default_nettype none",
         "module tt_um_duarte_diamantino_pid8 (input wire [7:0] ui_in, output wire [7:0] uo_out,",
         "    input wire [7:0] uio_in, output wire [7:0] uio_out, output wire [7:0] uio_oe,",
         "    input wire ena, input wire clk, input wire rst_n);"]
lines += [f"    wire {n};" for n in sorted(netname.values(), key=lambda s: int(s[1:]))]

errors = []
n_inst = 0
for p in d["parts"]:
    t, pid = p["type"], p["id"]
    if t in IGNORE:
        continue
    if t not in MODEL:
        errors.append(f"unknown part type {t} ({pid})")
        continue
    mod, ins, outs = MODEL[t]
    conns = []
    for pin in ins + outs:
        n = net_of(f"{pid}:{pin}")
        if n is None:
            if pin in ins:
                errors.append(f"unconnected input {pid}:{pin}")
            continue
        conns.append(f".{pin}({n})")
    lines.append(f"    {mod} {pid.replace('-', '_')} ({', '.join(conns)});")
    n_inst += 1

# host pins and constants
seen_out = set()
for root, members in nets.items():
    n = netname[root]
    for m in members:
        if m in HOST_IN:
            lines.append(f"    assign {n} = {HOST_IN[m]};")
        elif m in HOST_OUT:
            lines.append(f"    assign {HOST_OUT[m]} = {n};")
            seen_out.add(HOST_OUT[m])
        elif m.startswith("mega:GND"):
            lines.append(f"    assign {n} = 1'b0;")
        elif m == "mega:5V":
            lines.append(f"    assign {n} = 1'b1;")
    # the plant must see the same U bits as the host
    for m in members:
        if m.startswith("plant:U"):
            k = int(m[7:])
            if f"mega:{37 - k}" not in members:
                errors.append(f"{m} is not on the same net as mega:{37 - k}")
for i in range(3):
    lines.append(f"    assign uio_out[{i}] = 1'b0;")
lines.append("    assign uio_oe = 8'b1111_1000;")
lines.append("    wire _unused = &{ena, uio_in[7:3], 1'b0};")
lines.append("endmodule")
missing = [o for o in HOST_OUT.values() if o not in seen_out]
if missing:
    errors.append(f"outputs not connected to the host: {missing}")

lines.append("""
module wk_and2 (input wire A, B, output wire OUT); assign OUT = A & B; endmodule
module wk_or2  (input wire A, B, output wire OUT); assign OUT = A | B; endmodule
module wk_xor2 (input wire A, B, output wire OUT); assign OUT = A ^ B; endmodule
module wk_nand2(input wire A, B, output wire OUT); assign OUT = ~(A & B); endmodule
module wk_nor2 (input wire A, B, output wire OUT); assign OUT = ~(A | B); endmodule
module wk_xnor2(input wire A, B, output wire OUT); assign OUT = ~(A ^ B); endmodule
module wk_not  (input wire IN, output wire OUT); assign OUT = ~IN; endmodule
module wk_buf  (input wire IN, output wire OUT); assign OUT = IN; endmodule
module wk_mux2 (input wire A, B, SEL, output wire OUT); assign OUT = SEL ? B : A; endmodule
module wk_ffd  (input wire D, CLK, output reg Q);
    initial Q = 1'b1;                       // as observed in Wokwi
    always @(posedge CLK) Q <= D;
endmodule
module wk_ffdsr(input wire D, CLK, S, R, output reg Q);
    initial Q = 1'b0;
    always @(posedge CLK or posedge S or posedge R)
        if (R)      Q <= 1'b0;
        else if (S) Q <= 1'b1;
        else        Q <= D;
endmodule
`default_nettype wire""")

if errors:
    print("\n".join(errors[:20]))
    raise SystemExit(f"{len(errors)} errors")
with open(DST, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{DST}: {n_inst} part instances, {len(nets)} nets")
